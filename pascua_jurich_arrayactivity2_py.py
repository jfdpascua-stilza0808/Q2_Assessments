# Activity 2: Process Your Data (Input + Computation/Search with Arrays/Lists)


# 1. Input - 5 array values
print("Enter 5 array values:")
my_array = []
for i in range(5):
    value = input(f"Enter value {i + 1}: ")
    my_array.append(value)


print("\nOriginal Array:", my_array)


# 2. Traversal using loop - display elements with index
for index in range(len(my_array)):
    print(f"Index {index}: {my_array[index]}")


# 3. Update using indexing
index_to_update = int(input("\nInput Index to Update: "))
new_value = input("Input New Value: ")


if 0 <= index_to_update < len(my_array):
    my_array[index_to_update] = new_value
    print("Updated Array:", my_array)
else:
    print("Invalid index!")


# 4. Slicing - display portion of array
slice_range = input("Input Slice Range (start:end): ")
start, end = slice_range.split(":")
start = int(start)
end = int(end)


print(f"Sliced Array [{start}:{end}]:", my_array[start:end])


# 5. Search
search_item = input("Input Search Item: ")


if search_item in my_array:
    found_index = my_array.index(search_item)
    print(f"'{search_item}' FOUND at index {found_index}")
else:
    print(f"'{search_item}' NOT FOUND in the array")


print("\nFinal Array:", my_array)
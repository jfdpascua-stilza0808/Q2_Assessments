# Student Score Analyzer Mini-App

scores_data = [85, 90, 78, 92, 88]

def display_scores(scores):
    print("\n--- Current Student Scores ---")
    for i, s in enumerate(scores):
        print(f"Student #{i+1} (Index {i}): {s}")

def search_score(scores, target):
    if target in scores:
        idx = scores.index(target)
        print(f"✅ Score {target} found at Student #{idx+1} (Index {idx}).")
    else:
        print(f"❌ Score {target} not found in records.")

def compute_statistics(scores):
    if not scores:
        print("No scores available.")
        return
    avg = sum(scores) / len(scores)
    print(f"\n--- Score Statistics ---")
    print(f"Total Students: {len(scores)}")
    print(f"Average Score:  {avg:.2f}")
    print(f"Highest Score:  {max(scores)}")
    print(f"Lowest Score:   {min(scores)}")

def update_score(scores, index, new_score):
    if 0 <= index < len(scores):
        old_val = scores[index]
        scores[index] = new_score
        print(f"✅ Updated Index {index}: {old_val} -> {new_score}")
    else:
        print(f"❌ Invalid index! Must be between 0 and {len(scores)-1}.")

def run_mini_app():
    print("=== Welcome to Student Score Analyzer ===")

    # Demonstration Run
    display_scores(scores_data)
    compute_statistics(scores_data)

    print("\n--- Performing Search ---")
    search_score(scores_data, 92)

    print("\n--- Updating Score ---")
    update_score(scores_data, 2, 82) # Update 78 to 82

    display_scores(scores_data)
    compute_statistics(scores_data)

# Run the Mini-App
run_mini_app()

#Activity 3 (Graded or Non-Graded Formative Assessment): Data Analysis Mini App

# Initial data
speeds_data = [8.5, 9.2, 7.8, 10.1, 8.9]  # in km/h
runners_data = ["Juan", "Maria", "Jose", "Ana", "Pedro"]


def display_speeds(speeds, runners):
    print("\n--- Current Running Speeds ---")
    for i, s in enumerate(speeds):
        print(f"Runner #{i+1} {runners[i]} (Index {i}): {s} km/h")


def add_speed(speeds, runners):
    name = input("Enter runner name: ")
    try:
        speed = float(input("Enter running speed (km/h): "))
        runners.append(name)
        speeds.append(speed)
        print(f"Added {name} with {speed} km/h!")
    except ValueError:
        print("Invalid input! Please enter a number.")


def search_speed(speeds, runners):
    print("\n--- Search for Runner ---")
    name = input("Enter runner name to search: ")
    if name in runners:
        index = runners.index(name)
        print(f"Found '{name}' at index {index} with speed {speeds[index]} km/h")
    else:
        print(f"'{name}' NOT FOUND!")


def update_speed(speeds, runners):
    display_speeds(speeds, runners)
    try:
        index = int(input("\nEnter index to update: "))
        if 0 <= index < len(speeds):
            new_speed = float(input("Enter new speed (km/h): "))
            speeds[index] = new_speed
            print(f"Updated! {runners[index]} now has {new_speed} km/h")
            print("Updated List:", speeds)
        else:
            print("Invalid index!")
    except ValueError:
        print("Please enter a valid number!")


def analyze_speeds(speeds):
    print("\n--- Analysis ---")
    if not speeds:
        print("No data yet!")
        return
    total = 0
    for s in speeds:  # Traversal
        total += s
    average = total / len(speeds)
    fastest = max(speeds)
    slowest = min(speeds)
    print(f"Total Runners: {len(speeds)}")
    print(f"Average Speed: {average:.2f} km/h")
    print(f"Fastest Speed: {fastest} km/h")
    print(f"Slowest Speed: {slowest} km/h")
    print(f"Top 3 Fastest (Slicing): {sorted(speeds, reverse=True)[0:3]}")


def main_menu():
    while True:
        print("\n===== RUNNING SPEED ANALYZER =====")
        print("1. Display All Speeds")
        print("2. Add Runner & Speed")
        print("3. Search Runner")
        print("4. Update Speed")
        print("5. Analyze Speeds")
        print("6. Exit")

        choice = input("Choose an option (1-6): ")

        if choice == "1":
            display_speeds(speeds_data, runners_data)
        elif choice == "2":
            add_speed(speeds_data, runners_data)
        elif choice == "3":
            search_speed(speeds_data, runners_data)
        elif choice == "4":
            update_speed(speeds_data, runners_data)
        elif choice == "5":
            analyze_speeds(speeds_data)
        elif choice == "6":
            print("Thank you! Goodbye!")
            break
        else:
            print("Invalid choice! Try again.")


# Run the app
main_menu()

